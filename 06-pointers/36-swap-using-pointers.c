/*
 * Problem: Swap two numbers using pointers
 * Concept: Pointers, addresses and dereferencing
 *
 * Description:
 * This program swaps two numbers using pointers.
 * The swap is performed inside a function.
 */

#include <stdio.h>

void swap(int *a, int *b)
{
    int temp;

    temp = *a;
    *a = *b;
    *b = temp;
}

int main(void)
{
    int x, y;

    printf("Enter two numbers: ");
    scanf("%d %d", &x, &y);

    printf("Before swapping: x = %d, y = %d\n", x, y);

    swap(&x, &y);

    printf("After swapping: x = %d, y = %d\n", x, y);

    return 0;
}
